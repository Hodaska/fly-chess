#!/bin/bash
# Ночной прогон Фазы 3: пересчёт признаков на ИСПРАВЛЕННОМ тракте + обучение.
#
# Что изменилось против первого прогона (см. заметки проекта, раздел про Фазу 3):
#   1. Пороги гомеостаза калибруются один раз и ЗАМОРАЖИВАЮТСЯ. Раньше они
#      дрейфовали через весь прогон, и признаки кодировали «когда посчитали»
#      (R2=0.98) вместо «что на доске» (R2=0.13).
#   2. Съём широкий, по всему мозгу (2048 нейронов), а не с 1312 нисходящих.
#      Замер показал: до нисходящих сигнал о доске не доходит вообще
#      (R2=-0.18), а в зрительной зоне он силён (R2=+0.86).
#
# Датасет НЕ трогаем — data/dataset.parquet в порядке, 150k размеченных позиций.
#
# Проверено на выборке 20k: мозг дал 17.70% против 17.15% у прямой модели по
# доске, то есть догнал потолок задачи (раньше отставал вчетверо).
set -e
cd "$(dirname "$0")/.."

PY="./.venv/Scripts/python.exe"
# Длина окна симуляции. 100 — измеренный оптимум (probe_window.py):
#   25 шагов -> R2 0.616 (1.1 ч)   100 шагов -> R2 0.663 (4.6 ч)  <- лучшее
#   50 шагов -> R2 0.637 (2.3 ч)   200 шагов -> R2 0.616 (9.1 ч)  <- было, зря
# После ~100 шагов рекуррентный хаос начинает СТИРАТЬ входной сигнал, поэтому
# 200 шагов давали ровно то же качество, что 25, но в 8 раз дольше.
STEPS="${1:-100}"

echo "=== ночной прогон, окно симуляции: ${STEPS} шагов ==="
date

echo ""
echo "=== 1/3: пересчёт признаков (исправленный тракт) ==="
PYTHONUTF8=1 "$PY" scripts/cache_features.py \
    --dataset data/dataset.parquet \
    --out data/features_cache.npz \
    --steps "$STEPS" \
    --readout wide \
    --readout-size 2048

echo ""
echo "=== 2/3: обучение readout-головы ==="
PYTHONUTF8=1 "$PY" scripts/train_readout.py \
    --cache data/features_cache.npz \
    --out data/readout_model.pt \
    --epochs 60

echo ""
echo "=== 3/3: проверка на стартовой позиции ==="
PYTHONUTF8=1 "$PY" -m scripts.play_move --model data/readout_model.pt

echo ""
echo "=== ГОТОВО ==="
date
